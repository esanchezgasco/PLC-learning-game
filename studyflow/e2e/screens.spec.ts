import { test, expect } from '@playwright/test';
import path from 'node:path';
const OUT = process.env.SHOTS_DIR;
test.skip(!OUT, 'Només per generar captures (SHOTS_DIR)');
test('captures', async ({ page }) => {
  const shot = (n: string) => page.screenshot({ path: path.join(OUT!, n + '.png'), fullPage: true });
  await page.goto('/assignatures');
  await page.getByRole('button', { name: '+ Nova assignatura' }).click();
  await page.getByLabel('Nom').fill('Dret Administratiu');
  await page.getByRole('button', { name: 'Desa' }).click();
  await page.getByTestId('pdf-input').setInputFiles(path.resolve('e2e/fixtures/apunts-dret-administratiu.pdf'));
  await expect(page.getByText('Text extret', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: /Revisa l’estructura i crea/ }).click();
  await expect(page.getByText('Vista prèvia del text extret')).toBeVisible();
  await shot('03-estructura');
  await page.getByRole('button', { name: 'Crea els temes i el material d’estudi' }).click();
  await expect(page.getByText('Temes creats', { exact: true })).toBeVisible();
  await shot('02-assignatura');
  await page.getByRole('link', { name: /Tema 1\./ }).click();
  await page.getByRole('link', { name: /1\.3\./ }).first().click();
  await expect(page.getByText(/Definició ·/).first()).toBeVisible();
  await shot('04-teoria');
  await page.getByRole('button', { name: 'Comença la pràctica' }).click();
  await expect(page.getByText(/Pregunta 1 de/)).toBeVisible();
  if (await page.locator('input[type=radio]').count()) await page.locator('input[type=radio]').first().check();
  else if (await page.getByRole('radio', { name: 'Vertader' }).count()) await page.getByRole('radio', { name: 'Vertader' }).click();
  else await page.getByLabel('Resposta').fill('nul·litat');
  await page.getByRole('button', { name: 'Comprova' }).click();
  await shot('05-practica');
  await page.goto('/');
  await shot('01-inici');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  await shot('06-inici-fosc');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => document.documentElement.classList.remove('dark'));
  await page.goto('/repas');
  await shot('07-repas-mobil');
});
